# src/rhosocial/github_actions_tracker/schema/ddl_postgres.py
"""PostgreSQL rendering of the schema through the expression system.

The service executes *this*, and so does everything else that reads the schema.
The point is not novelty: the expression system is the backend's own statement
builder, so a table created through it is created by the same machinery that
formats queries, and a defect in that machinery shows up here rather than in a
string this project hand-maintains.

What this module demonstrates, one construct per helper below: the expression
system can express every feature this schema uses -- serial/identity columns,
typed columns with length, ``NOT NULL``/``DEFAULT``/``PRIMARY KEY``/``UNIQUE``,
single-column foreign keys with ``ON DELETE CASCADE``, table-level unique
constraints over column tuples, and standalone indexes. That is the whole
vocabulary of the schema in :mod:`schema.model`; if a new column needs a feature
beyond it, the model gains a construct and both renderers learn it.

Two details the renderer has to get right, both of which the plain-SQL renderer
gets for free by being text:

* a constraint must be wrapped in its production node -- ``ColumnConstraint``
  around a branch, ``TableConstraint`` around a table branch -- because the
  grammar puts the ``CONSTRAINT``-level traits there;
* ``DEFAULT NOW()`` is a call, not a string. Passing the text ``"NOW()"`` to the
  default branch renders a quoted literal, which silently becomes the string
  ``'NOW()'`` in the database.
"""

from __future__ import annotations

from functools import lru_cache
from typing import TYPE_CHECKING, Any

from .model import Column, ColumnType, DefaultNow, ForeignKey, Table

if TYPE_CHECKING:
    from rhosocial.activerecord.backend.impl.postgres.backend import AsyncPostgresBackend

#: The server version the dialect is built for. Only affects rendering of
#: version-gated syntax; nothing here is gated.
_POSTGRES_VERSION = (18, 0, 0)


@lru_cache(maxsize=1)
def dialect():
    """Return the Postgres dialect used to render this schema.

    Cached because constructing it walks the dialect's mixin chain, which is not
    free and never varies.
    """
    from rhosocial.activerecord.backend.impl.postgres.dialect import PostgresDialect

    return PostgresDialect(_POSTGRES_VERSION)


def _data_type(column: Column, *, plain_integer_for_identity: bool = False) -> Any:
    """Build the expression-system type node for a column.

    ``plain_integer_for_identity`` keeps a surrogate key as a plain ``INTEGER``
    when the ``GENERATED BY DEFAULT AS IDENTITY`` clause is going to spell out
    the auto-increment: ``SERIAL`` plus an identity clause would state the same
    fact twice, and the identity form is the one that carries the version gate.

    Raises:
        KeyError: The column type has no mapping; the schema and this table must
            be extended together.
    """
    from rhosocial.activerecord.backend.expression.types import (
        BigIntType,
        BooleanType,
        IntegerType,
        JsonBType,
        TextType,
        VarCharType,
    )
    from rhosocial.activerecord.backend.expression.types.datetime_ import (
        DateType,
        TimestampTzType,
    )
    from rhosocial.activerecord.backend.impl.postgres.expression.types import (
        PostgresSerialType,
    )

    d = dialect()
    builders = {
        ColumnType.SERIAL: (
            (lambda: IntegerType(d))
            if plain_integer_for_identity
            else (lambda: PostgresSerialType(d))
        ),
        ColumnType.INTEGER: lambda: IntegerType(d),
        ColumnType.BIGINT: lambda: BigIntType(d),
        ColumnType.VARCHAR: lambda: VarCharType(d, column.length or 255),
        ColumnType.TEXT: lambda: TextType(d),
        ColumnType.BOOLEAN: lambda: BooleanType(d),
        ColumnType.TIMESTAMPTZ: lambda: TimestampTzType(d),
        ColumnType.JSONB: lambda: JsonBType(d),
        ColumnType.DATE: lambda: DateType(d),
    }
    return builders[column.type]()


def _default_value(column: Column) -> Any:
    """Turn a column's declared default into an expression node.

    The default reaches SQL through the expression system's own value channel:
    a Python value passed to ``ColumnDefaultConstraint`` is wrapped in an
    ``inline=True`` literal by ``DefaultValueClause``, which is what a DDL
    position requires (it accepts no bind parameters). No raw SQL is involved --
    that is the point of using the builder at all.

    ``DefaultNow`` is the one case that is a call rather than a value, so it
    becomes a ``FunctionCall``. Passing the text ``"NOW()"`` as a string would
    have rendered a quoted literal that silently stops being a timestamp.

    Raises:
        TypeError: The default is a type the expression system has no value node
            for.
    """
    from rhosocial.activerecord.backend.expression.functions import current_timestamp

    value = column.default
    if isinstance(value, DefaultNow):
        return current_timestamp(dialect())
    if isinstance(value, (bool, int, float, str)):
        # A plain value: ColumnDefaultConstraint wraps it as an inline literal.
        return value
    raise TypeError(
        f"column '{column.name}' has a default of type {type(value).__name__}, "
        "which the expression system has no node for"
    )


def _column_definition(column: Column, *, table_is_partitioned: bool = False) -> Any:
    """Build a ``ColumnDefinition`` with its constraints wrapped as productions.

    An auto-increment key is rendered as ``GENERATED BY DEFAULT AS IDENTITY`` by
    the backend itself, from the primary-key constraint's flag -- so the type
    stays plain ``INTEGER`` rather than ``SERIAL``. Two spellings of one fact
    would be one too many, and the identity form is the one that also carries the
    version gate (PostgreSQL 9 refuses here instead of rendering a clause its
    server rejects).

    A column-level ``UNIQUE`` is *dropped* on a partitioned table and re-declared
    at table level with the partition column added: PostgreSQL rejects a unique
    key that does not contain the partition column, and a table-level constraint
    is the only place the two can be spelled together.
    """
    from rhosocial.activerecord.backend.expression.statements.ddl_table import (
        ColumnConstraint,
        ColumnDefaultConstraint,
        ColumnDefinition,
        ColumnNotNullConstraint,
        ColumnPrimaryKeyConstraint,
        ColumnUniqueConstraint,
    )

    d = dialect()
    constraints = []
    if column.primary_key and not table_is_partitioned:
        constraints.append(
            ColumnConstraint(d, branch=ColumnPrimaryKeyConstraint(d, is_auto_increment=True))
        )
    elif column.primary_key or not column.nullable:
        # The partition-keyed key moves to table level (see
        # :func:`_primary_key_constraint`), but its column is still not
        # nullable: a primary key column is implicitly NOT NULL, and on a
        # partitioned table the table-level declaration does not add it for the
        # columns it names.
        constraints.append(ColumnConstraint(d, branch=ColumnNotNullConstraint(d)))
    if column.unique and not table_is_partitioned:
        constraints.append(ColumnConstraint(d, branch=ColumnUniqueConstraint(d)))
    if column.default is not None:
        constraints.append(
            ColumnConstraint(d, branch=ColumnDefaultConstraint(d, _default_value(column)))
        )
    identity: list[Any] = []
    if table_is_partitioned and column.primary_key:
        # On a partitioned table the key is declared at table level (it must
        # contain the partition column), which takes the column-level PRIMARY
        # KEY -- and with it the backend's automatic identity clause. Said here
        # instead, so the surrogate stays ``GENERATED BY DEFAULT AS IDENTITY``:
        # the server fills it, the ORM leaves it out of the INSERT, and the
        # model declares it an identity key. The ``attributes`` channel is where
        # such a clause belongs -- the constraints channel carries only
        # constraint branches.
        from rhosocial.activerecord.backend.expression.statements.ddl_table import IdentityClause

        identity.append(IdentityClause(d, "BY DEFAULT"))

    return ColumnDefinition(
        d,
        column.name,
        _data_type(column, plain_integer_for_identity=column.primary_key),
        attributes=identity or None,
        constraints=constraints or None,
    )
    """Build a ``ColumnDefinition`` with its constraints wrapped as productions.

    A column-level ``UNIQUE`` is *dropped* on a partitioned table and re-declared
    at table level with the partition column added: PostgreSQL rejects a unique
    key that does not contain the partition column, and a table-level constraint
    is the only place the two can be spelled together.
    """
    from rhosocial.activerecord.backend.expression.statements.ddl_table import (
        ColumnConstraint,
        ColumnDefaultConstraint,
        ColumnDefinition,
        ColumnNotNullConstraint,
        ColumnPrimaryKeyConstraint,
        ColumnUniqueConstraint,
    )

    d = dialect()
    constraints = []
    if column.primary_key and not table_is_partitioned:
        constraints.append(
            ColumnConstraint(d, branch=ColumnPrimaryKeyConstraint(d, is_auto_increment=True))
        )
    elif column.primary_key or not column.nullable:
        # The partition-keyed key moves to table level (see
        # :func:`_primary_key_constraint`), but its column is still not
        # nullable: a primary key column is implicitly NOT NULL, and on a
        # partitioned table the table-level declaration does not add it for the
        # columns it names.
        constraints.append(ColumnConstraint(d, branch=ColumnNotNullConstraint(d)))
    if column.unique and not table_is_partitioned:
        constraints.append(ColumnConstraint(d, branch=ColumnUniqueConstraint(d)))
    if column.default is not None:
        constraints.append(
            ColumnConstraint(d, branch=ColumnDefaultConstraint(d, _default_value(column)))
        )

    return ColumnDefinition(d, column.name, _data_type(column), constraints=constraints or None)


def _table_constraint(key: ForeignKey) -> Any:
    """Build a table-level ``FOREIGN KEY`` wrapped in its production node."""
    from rhosocial.activerecord.backend.expression.objects import Table
    from rhosocial.activerecord.backend.expression.statements.ddl_table import (
        ReferentialAction,
        TableConstraint,
        TableForeignKeyConstraint,
    )

    d = dialect()
    return TableConstraint(
        d,
        branch=TableForeignKeyConstraint(
            d,
            [key.column],
            (Table(d, key.references_table), [key.references_column]),
            on_delete=ReferentialAction(key.on_delete.value) if key.on_delete else None,
        ),
    )


def _unique_constraint(columns: tuple[str, ...], partition_column: str | None = None) -> Any:
    """Build a table-level ``UNIQUE`` over one or more columns.

    On a partitioned table the partition column is appended, because PostgreSQL
    requires every unique and primary key to contain it: "one log per job" then
    reads ``UNIQUE (job_id, bucket)``, which is the *same* rule -- the bucket is a
    function of the row's own job, so two rows that would have collided collide
    just the same. Only a writer that invented its own bucket could break it, and
    there is exactly one function that computes it.
    """
    from rhosocial.activerecord.backend.expression.statements.ddl_table import (
        TableConstraint,
        TableUniqueConstraint,
    )

    d = dialect()
    names = list(columns)
    if partition_column is not None and partition_column not in names:
        names.append(partition_column)
    return TableConstraint(d, branch=TableUniqueConstraint(d, names))


def _primary_key_constraint(columns: tuple[str, ...], partition_column: str | None = None) -> Any:
    """Build a table-level ``PRIMARY KEY``, with the partition column appended.

    Same rule and same reasoning as :func:`_unique_constraint`: on a partitioned
    table a primary key without the partition column is refused by the server
    outright -- ``unique constraint on partitioned table must include all
    partitioning columns`` -- and the pair ``(id, bucket)`` is the same key
    ``(id)`` was, because the bucket is part of what identifies the row.
    """
    from rhosocial.activerecord.backend.expression.statements.ddl_table import (
        TableConstraint,
        TablePrimaryKeyConstraint,
    )

    d = dialect()
    names = list(columns)
    if partition_column is not None and partition_column not in names:
        names.append(partition_column)
    return TableConstraint(d, branch=TablePrimaryKeyConstraint(d, names))


def _partition_clause(table: Table) -> Any:
    """Build the ``PARTITION BY RANGE`` clause, when the table is partitioned.

    The monthly bucket is a range over one date column -- ``bucket`` -- and the
    strategy enum is the expression system's: a clause the backend's own
    formatter renders, rather than a string this project maintains.
    """
    from rhosocial.activerecord.backend.expression import Column as ColumnNode
    from rhosocial.activerecord.backend.expression import PartitionClause, PartitionStrategy

    d = dialect()
    return PartitionClause(
        d,
        method=PartitionStrategy.RANGE,
        keys=[ColumnNode(d, table.partition.column)],
    )


def render_create_table(table: Table) -> str:
    """Render one ``CREATE TABLE IF NOT EXISTS`` through the expression system.

    Args:
        table: The table definition.

    Returns:
        The statement text, without a trailing semicolon.

    Raises:
        ValueError: The expression system emitted bind parameters. A DDL
            statement must be self-contained; parameters would mean something
            was rendered as a value that should have been inline.
    """
    from rhosocial.activerecord.backend.expression.objects import Table as TableNode
    from rhosocial.activerecord.backend.expression.statements.ddl_table import (
        CreateTableStatement,
    )

    d = dialect()
    # On a partitioned table PostgreSQL requires the partition column to be part
    # of *every* key -- the primary key included -- and a column-level constraint
    # is the one place it cannot be spelled together with the partition column. So
    # the column-level ``PRIMARY KEY`` and ``UNIQUE`` move to table level here and
    # the partition column is appended to each.
    partition_column = table.partition.column if table.partition is not None else None
    primary_key_columns: tuple[str, ...] = ()
    column_uniques: list[str] = []
    if partition_column is not None:
        primary_key_columns = tuple(column.name for column in table.columns if column.primary_key)
        column_uniques = [
            column.name for column in table.columns if column.unique and not column.primary_key
        ]

    statement = CreateTableStatement(
        d,
        table=TableNode(d, table.name),
        if_not_exists=True,
        partition=_partition_clause(table) if table.partition is not None else None,
        columns=[
            _column_definition(column, table_is_partitioned=partition_column is not None)
            for column in table.columns
        ],
        table_constraints=[
            *(
                [_primary_key_constraint(primary_key_columns, partition_column)]
                if primary_key_columns
                else []
            ),
            *(_table_constraint(key) for key in table.foreign_keys),
            *(
                _unique_constraint(unique.columns, partition_column)
                for unique in table.unique_constraints
            ),
            *(_unique_constraint((name,), partition_column) for name in column_uniques),
        ],
    )
    sql, params = statement.to_sql()
    if params:
        raise ValueError(
            f"DDL for '{table.name}' produced bind parameters {params!r}; "
            "a schema statement must render inline"
        )
    return sql


def render_create_index(table: Table) -> list[str]:
    """Render one table's index statements through the expression system.

    A GIN index carries an operator class on its column, which the expression
    system does not render (``format_create_index_statement`` emits column names
    only). Such an index is therefore *skipped* here and created by
    :func:`schema.ensure_accelerator_indexes` as an explicit statement -- and the
    declaration in the model remains the one place the intent is written down.
    """
    from rhosocial.activerecord.backend.expression.objects import Index as IndexNode
    from rhosocial.activerecord.backend.expression.objects import Table as TableNode
    from rhosocial.activerecord.backend.expression.statements.ddl_index import (
        CreateIndexStatement,
    )

    d = dialect()
    statements = []
    for index in table.indexes:
        if index.method == "gin" or index.opclass:
            continue
        sql, params = CreateIndexStatement(
            d,
            index=IndexNode(d, index.name),
            table=TableNode(d, table.name),
            columns=list(index.columns),
            unique=index.unique,
            if_not_exists=True,
        ).to_sql()
        if params:
            raise ValueError(f"index '{index.name}' produced bind parameters {params!r}")
        statements.append(sql)
    return statements


def drop_statements(schema: Any) -> list[str]:
    """Render the ``DROP TABLE`` statements, dependants first, legacy included.

    Plain text on purpose: a drop is a name list, and the expression system's
    builder is for statements whose shape can vary. It also drops a partitioned
    parent with one statement, which takes its partitions with it -- the reason a
    teardown never has to know that a table became a partition set.
    """
    names = (*schema.drop_order(), *schema.legacy_tables)
    return [f'DROP TABLE IF EXISTS "{name}" CASCADE' for name in names]


def render_schema_script(schema: Any) -> str:
    """Render the whole schema as one script, for a human reading a change.

    The statements are the ones the service executes, so a review reads the
    deployed shape -- including ``PARTITION BY`` -- rather than a hand-kept
    parallel text that can only ever be *nearly* the same.
    """
    return ";\n\n".join(render_schema(schema)) + ";\n"


def render_schema(schema: Any) -> list[str]:
    """Render every table and index as individual statements.

    Statements are returned separately rather than as one script: the driver
    executes them one at a time, and a failure points at one statement.

    Args:
        schema: The schema to render.

    Returns:
        ``CREATE TABLE`` statements followed by their ``CREATE INDEX``
        statements, in schema order.
    """
    statements: list[str] = []
    for table in schema.all_tables():
        statements.append(render_create_table(table))
        statements.extend(render_create_index(table))
    return statements


async def create_all(backend: AsyncPostgresBackend, schema: Any) -> None:
    """Create every table and index on ``backend``."""
    from .model import SCHEMA as DEFAULT_SCHEMA

    for statement in render_schema(schema or DEFAULT_SCHEMA):
        await backend.execute(statement)


