# tests/models/test_repo_webhook_secret.py
"""One secret per repository, and none of them is shared.

The service used to hold one key for every hook, which made two questions
unanswerable: "does this repository have a secret of its own?" (a repository with
no row passed anyway) and "what do I rotate?" (rotating meant reconfiguring every
repository at once). Both are answered here, and the answer to the first one is
allowed to be "no" -- visibly.

GitHub never returns a hook's secret, so taking over an existing hook can only
mean rotating it. That is why there is no "read the current secret" path: the
value must be supplied by the operator or generated by us.
"""

from __future__ import annotations

import pytest

from rhosocial.github_actions_tracker.models import (
    AsyncRepository,
    AsyncRepoWebhookSecret,
    Repository,
    RepoWebhookSecret,
)
from rhosocial.github_actions_tracker.models.webhook_secret import (
    STATE_PENDING_USER,
    STATE_PUSHED,
    STATE_UNKNOWN,
)


async def _repo(full_name: str = "acme/demo", github_id: int = 99) -> AsyncRepository:
    owner, _, name = full_name.partition("/")
    repo = AsyncRepository(github_repo_id=github_id, full_name=full_name, owner=owner, name=name)
    await repo.save()
    return repo


class TestTheRow:
    async def test_a_repository_starts_without_a_secret(self, bound) -> None:
        repo = await _repo()
        assert await AsyncRepoWebhookSecret.for_repository(repo.id or 0) is None, (
            "no row is a real answer: the receiver refuses such a delivery rather "
            "than testing it against a shared key"
        )

    async def test_set_stores_the_value_and_the_state(self, bound) -> None:
        repo = await _repo()
        record = await AsyncRepoWebhookSecret.set(repo.id or 0, "s3cret", state=STATE_UNKNOWN)
        assert record.secret == "s3cret"
        assert record.state == STATE_UNKNOWN

    async def test_set_replaces_rather_than_duplicates(self, bound) -> None:
        """Rotation keeps the row: the repository id is the subscription."""
        repo = await _repo()
        first = await AsyncRepoWebhookSecret.set(repo.id or 0, "one")
        second = await AsyncRepoWebhookSecret.set(repo.id or 0, "two")

        assert second.id == first.id
        assert second.secret == "two"
        rows = await AsyncRepoWebhookSecret.query().all()
        assert len(rows) == 1

    async def test_rotate_generates_a_different_value(self, bound) -> None:
        repo = await _repo()
        first = await AsyncRepoWebhookSecret.set(repo.id or 0, "old")
        rotated = await AsyncRepoWebhookSecret.rotate(repo.id or 0)
        assert rotated.secret != first.secret
        assert len(rotated.secret) == len(RepoWebhookSecret.generate_secret())

    async def test_an_empty_secret_is_refused(self, bound) -> None:
        repo = await _repo()
        with pytest.raises(ValueError):
            await AsyncRepoWebhookSecret.set(repo.id or 0, "   ")

    async def test_clear_removes_the_row(self, bound) -> None:
        repo = await _repo()
        await AsyncRepoWebhookSecret.set(repo.id or 0, "s3cret")
        assert await AsyncRepoWebhookSecret.clear(repo.id or 0) is True
        assert await AsyncRepoWebhookSecret.for_repository(repo.id or 0) is None
        assert await AsyncRepoWebhookSecret.clear(repo.id or 0) is False


class TestTheStates:
    async def test_pending_means_the_operator_still_has_work(self, bound) -> None:
        repo = await _repo()
        record = await AsyncRepoWebhookSecret.set(repo.id or 0, "s3cret")
        assert record.state == STATE_PENDING_USER
        assert record.pending is True

    async def test_pushed_means_it_is_already_on_github(self, bound) -> None:
        repo = await _repo()
        record = await AsyncRepoWebhookSecret.set(repo.id or 0, "s3cret", state=STATE_PUSHED)
        assert record.pending is False

    async def test_the_summary_counts_each_state(self, bound) -> None:
        for index, state in enumerate((STATE_PUSHED, STATE_PENDING_USER, STATE_UNKNOWN)):
            repo = await _repo(f"acme/repo{index}", github_id=100 + index)
            await AsyncRepoWebhookSecret.set(repo.id or 0, "s3cret", state=state)

        summary = await AsyncRepoWebhookSecret.states_summary()
        assert summary == {STATE_PUSHED: 1, STATE_PENDING_USER: 1, STATE_UNKNOWN: 1}


class TestTheSecretStaysOutOfResponses:
    async def test_describe_never_returns_the_value(self, bound) -> None:
        repo = await _repo()
        record = await AsyncRepoWebhookSecret.set(repo.id or 0, "s3cret-value")
        described = record.describe()
        assert "secret" not in described
        assert "s3cret-value" not in str(described)

    async def test_the_sync_twin_writes_the_same_table(self) -> None:
        assert RepoWebhookSecret.__table_name__ == AsyncRepoWebhookSecret.__table_name__
        assert Repository.webhook_secret is not None, (
            "the inverse relation is what makes the row reachable from the "
            "repository a caller already holds"
        )
